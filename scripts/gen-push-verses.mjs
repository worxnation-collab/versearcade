// The daily verse's REFERENCE, in rotation order, for push-send.
//
// The come-back push (0168) names today's verse and nothing else — and the
// rotation lives only in the app (`getVerseForDate`, a fixed shuffle of the
// whole pool). An Edge Function cannot import `src/`, and a verse written to a
// table by a client would let any client choose the words every lapsed player
// is sent. So the order is GENERATED into the function's own folder from the
// app's real `getVerseForDate`, and this script runs in `npm run build` as a
// check: appending to VERSE_POOL changes the rotation, and a stale copy would
// push one verse while the app opened another — which renders perfectly.
//
//   node scripts/gen-push-verses.mjs           # check (the build)
//   node scripts/gen-push-verses.mjs --write   # regenerate the file

import { build } from 'esbuild'
import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..')
const target = path.join(root, 'supabase/functions/push-send/verseOrder.ts')
const out = path.join(fs.mkdtempSync(path.join(os.tmpdir(), 'pv-')), 'pv.mjs')
const entry = path.join(path.dirname(out), 'entry.ts')
fs.writeFileSync(entry, `export { getVerseForDate } from ${JSON.stringify(path.join(root, 'src/data/bible/questions.ts'))}
export { VERSE_POOL } from ${JSON.stringify(path.join(root, 'src/data/bible/pool.ts'))}\n`)
await build({
  entryPoints: [entry],
  bundle: true, format: 'esm', platform: 'node', outfile: out, logLevel: 'error',
  alias: { '@': path.join(root, 'src') },
  define: { 'import.meta.env': '{}' },
})
const { getVerseForDate, VERSE_POOL } = await import(out)

// Slot k is the verse for every day whose day number ≡ k (mod N). Day 0 is
// 1970-01-01, so the date for slot k is simply the epoch plus k days.
const size = VERSE_POOL.length
const day = (k) => new Date(Date.UTC(1970, 0, 1 + k)).toISOString().slice(0, 10)
const order = Array.from({ length: size }, (_, k) => getVerseForDate(day(k)).reference)

const body = `// GENERATED by scripts/gen-push-verses.mjs from the app's getVerseForDate —
// do not edit by hand; run \`node scripts/gen-push-verses.mjs --write\`.
// Slot k is the daily verse for every date whose UTC day number ≡ k (mod ${size}).
export const VERSE_ORDER: string[] = ${JSON.stringify(order, null, 0).replace(/","/g, '",\n  "').replace('["', '[\n  "').replace('"]', '",\n]')}

// The reference the app plays on this LOCAL date (YYYY-MM-DD).
export function verseRefFor(date: string): string {
  const [y, m, d] = date.split('-').map(Number)
  const n = Math.floor(Date.UTC(y || 1970, (m || 1) - 1, d || 1) / 86400000)
  const N = VERSE_ORDER.length
  return VERSE_ORDER[((n % N) + N) % N]
}
`
if (process.argv.includes('--write')) {
  fs.writeFileSync(target, body)
  console.log(`gen-push-verses: wrote ${size} references`)
} else {
  const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
  if (have !== body) {
    console.error('gen-push-verses: supabase/functions/push-send/verseOrder.ts is stale — run `node scripts/gen-push-verses.mjs --write`')
    process.exit(1)
  }
  console.log(`check:push-verses ok (${size} references)`)
}
