// What kind of word each answer in a generated cross is — noun, verb,
// adjective — so its clue can say so, the way a printed crossword does.
//
// The authored puzzles in `crossword.ts` carry a `pos` written by hand, in
// context, for every one of their 104 words. The ~10,900 crosses that
// `crossGen.ts` cuts on demand have nobody to write one, so this is the second
// source: a lexicon of the pool's cross-eligible vocabulary, keyed by the word
// as it stands in a cross (upper case, apostrophes dissolved — "God's" is GODS).
//
// Three rules, and the third is the one that matters:
//
//  1. **A word is here only if it is the SAME kind of word in every verse of
//     the pool that uses it.** LOVE, HOPE, REST, LIGHT, FEAR, TRUST, WORK and
//     about two hundred more are deliberately absent: "God is love" and "love
//     one another" are one spelling and two parts of speech, and a per-word
//     table cannot tell which verse it is standing in. The clue for one of
//     those simply shows no type — the label reads exactly as it did before
//     this file existed.
//  2. **A missing word is not an error.** `wordTypeOf` returns undefined and
//     the screen leaves the type off. Nothing here can leave a cross unbuilt
//     or a clue blank, the same fail-closed shape every catalog here has.
//  3. **A wrong type is worse than none**, which is why this was not simply
//     generated. The list was DRAFTED by running a part-of-speech tagger over
//     every pool verse and keeping only the words it tagged consistently, then
//     every word was read by hand against the verses it appears in, with ~330
//     corrections and drops applied (capitalised nouns the tagger read as
//     names, "the poor" that is a noun and an adjective, and so on). Add to it
//     by hand, in context, and add a word to exactly ONE list — a word in two
//     is a contradiction, and `checkCrossGen()` fails on it.
//
// `name` is a proper noun — a person or a place — and is labelled "name" on
// screen because that is what a player would call it.

