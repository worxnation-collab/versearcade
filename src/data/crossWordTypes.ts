const WORD_TYPES: ReadonlyMap<string, WordType> = (() => {
  const map = new Map<string, WordType>()
  for (const type of Object.keys(WORD_LISTS) as WordType[]) {
    for (const w of WORD_LISTS[type].split(/\s+/).filter(Boolean)) map.set(w, type)
  }
  return map
})()

/** The type of a cross answer, or undefined when the lexicon cannot say. */
export function wordTypeOf(word: string): WordType | undefined {
  return WORD_TYPES.get(word.toUpperCase())
}

/**
 * The raw lists, for `checkCrossGen()`: every entry must be A–Z, and no word
 * may sit in two lists — a lookup map would silently keep the last one.
 */
export function wordTypeEntries(): Array<[string, WordType]> {
  const out: Array<[string, WordType]> = []
  for (const type of Object.keys(WORD_LISTS) as WordType[]) {
    for (const w of WORD_LISTS[type].split(/\s+/).filter(Boolean)) out.push([w, type])
  }
  return out
}
